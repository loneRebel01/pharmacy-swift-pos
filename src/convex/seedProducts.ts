export const seedAllMedicines = internalMutation({
  args: {},
  handler: async (ctx) => {
    // Check if products already exist to avoid duplicates
    const existing = await ctx.db.query("products").collect();
    const existingNames = new Set(existing.map((p) => p.name.toLowerCase()));

    let added = 0;
    let skipped = 0;

    for (let i = 0; i < MEDICINE_NAMES.length; i++) {
      const name = MEDICINE_NAMES[i];
      if (existingNames.has(name.toLowerCase())) {
        skipped++;
        continue;
      }

      const code = `MED-${String(i + 1).padStart(4, "0")}`;
      await ctx.db.insert("products", {
        code,
        name,
        unit: "pcs",
        purchasePrice: 0,
        retailPrice: 0,
        currentStock: 0,
        isActive: true,
        createdAt: Date.now(),
        updatedAt: Date.now(),
      });
      added++;
    }

    return { added, skipped, total: MEDICINE_NAMES.length };
  },
});
